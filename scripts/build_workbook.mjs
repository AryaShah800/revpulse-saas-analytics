import fs from 'node:fs/promises';
import path from 'node:path';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const root=path.resolve(import.meta.dirname,'../..');
const data=JSON.parse(await fs.readFile(path.join(import.meta.dirname,'workbook_input.json'),'utf8'));
const wb=Workbook.create();
const names=['Overview','Cleaned_Master','Customers','Payments','Audit_Pivots','Reconciliation'];
const sheets=Object.fromEntries(names.map(name=>[name,wb.worksheets.add(name)]));
const ink='#19324F',blue='#255EA8',muted='#EAF0F7';
const currency='"₹"#,##0.00;("₹"#,##0.00);"—"';
function table(sheet,headers,rows,name){
 sheet.getRangeByIndexes(0,0,1,headers.length).values=[headers];
 if(rows.length)sheet.getRangeByIndexes(1,0,rows.length,headers.length).values=rows;
 sheet.tables.add(sheet.getRangeByIndexes(0,0,rows.length+1,headers.length),true,name);
 sheet.getRangeByIndexes(0,0,rows.length+1,headers.length).format.font={name:'Arial',size:10,color:ink};
 sheet.getRangeByIndexes(0,0,1,headers.length).format={fill:ink,font:{name:'Arial',size:10,color:'#FFFFFF',bold:true},rowHeight:28};
 sheet.getUsedRange().format.columnWidth=20;sheet.freezePanes.freezeRows(1);
}
for(const sheet of Object.values(sheets)){sheet.showGridLines=false;sheet.getRange('A1:L30').format.font={name:'Arial',size:10,color:ink};}
table(sheets.Customers,['Customer ID','Company','Region','Channel'],data.customers,'CustomersTable');
sheets.Customers.getRange('B:B').format.columnWidth=36;
const invoiceRows=data.invoices.map(row=>row.map((v,i)=>i===2||i===3?new Date(v+'T00:00:00Z'):v));
table(sheets.Cleaned_Master,['Invoice ID','Customer ID','Issue date','Due date','Plan','Amount INR','Outstanding INR','Days overdue','Region','Channel'],invoiceRows.map(r=>[...r,null,null]),'InvoiceTable');
const n=invoiceRows.length+1,c=data.customers.length+1,p=data.delays.length+1;
sheets.Cleaned_Master.getRange(`C2:D${n}`).setNumberFormat('dd-mmm-yyyy');
sheets.Cleaned_Master.getRange(`F2:G${n}`).setNumberFormat(currency);
sheets.Cleaned_Master.getRange('A:A').format.columnWidth=30;
sheets.Cleaned_Master.getRange('I2').formulas=[[`=_xlfn.XLOOKUP(B2,Customers!$A$2:$A$${c},Customers!$C$2:$C$${c},"UNMAPPED",0)`]];
sheets.Cleaned_Master.getRange(`I2:I${n}`).fillDown();
sheets.Cleaned_Master.getRange('J2').formulas=[[`=_xlfn.XLOOKUP(B2,Customers!$A$2:$A$${c},Customers!$D$2:$D$${c},"UNMAPPED",0)`]];
sheets.Cleaned_Master.getRange(`J2:J${n}`).fillDown();
sheets.Cleaned_Master.getRange(`E2:E${n}`).dataValidation={rule:{type:'list',values:['Starter','Growth','Enterprise']}};
sheets.Cleaned_Master.getRange(`H2:H${n}`).dataValidation={rule:{type:'whole',operator:'greaterThanOrEqual',formula1:0}};
sheets.Cleaned_Master.getRange(`G2:H${n}`).conditionalFormats.add('cellIs',{operator:'greaterThan',formula:0,format:{fill:'#FCE9E7',font:{color:'#9B2727'}}});
table(sheets.Payments,['Event ID','Invoice ID','Plan','Delay days'],data.delays,'PaymentsTable');
sheets.Payments.getRange('A:B').format.columnWidth=35;
const overview=sheets.Overview;
overview.getRange('B2').values=[['RevPulse validation audit']];overview.getRange('B2').format.font={name:'Arial',size:16,bold:true,color:ink};
overview.getRange('B4').values=[[`Reporting period: ${data.start} to ${data.cutoff}`]];
overview.getRange('B6:C6').values=[['Metric','Value']];
overview.getRange('B7:B9').values=[['Invoiced amount (INR)'],['Invoice count'],['Payment event count']];
overview.getRange('C7:C9').formulas=[[`=SUM(Cleaned_Master!F2:F${n})`],[`=COUNTA(Cleaned_Master!A2:A${n})`],[`=COUNTA(Payments!A2:A${p})`]];
overview.getRange('C7').setNumberFormat(currency);
overview.getRange('B12').values=[['Source: RevPulse synthetic operational simulation. No real customer data.']];
overview.getRange('B14').values=[['Amounts include simulated tax and one-time charges; they are invoicing, not MRR.']];
overview.getRange('B16').values=[['Payment delay is per successful payment event; negative values mean early payment.']];
overview.getRange('B18').values=[['Refresh: rerun the pipeline and workbook builder for a new reporting snapshot.']];
overview.getRange('B20').values=[['Audit_Pivots contains native PivotTables; refresh them after editing source rows.']];
overview.getRange('B22').values=[['Validation dropdowns guide edits. Imported records were validated by the pipeline.']];
overview.getRange('B:B').format.columnWidth=38;overview.getRange('C:C').format.columnWidth=26;
const piv=sheets.Audit_Pivots;
piv.getRange('B2').values=[['Regional invoicing']];piv.getRange('B4:C4').values=[['Region','Invoiced INR']];
piv.getRange('F2').values=[['Payment delay by plan']];piv.getRange('F4:G4').values=[['Plan','Average delay days']];
data.regional.forEach(([region],i)=>{piv.getCell(i+4,1).values=[[region]];piv.getCell(i+4,2).formulas=[[`=SUMIFS(Cleaned_Master!$F$2:$F$${n},Cleaned_Master!$I$2:$I$${n},B${i+5})`]];});
data.plan_delay.forEach(([plan],i)=>{piv.getCell(i+4,5).values=[[plan]];piv.getCell(i+4,6).formulas=[[`=AVERAGEIFS(Payments!$D$2:$D$${p},Payments!$C$2:$C$${p},F${i+5})`]];});
piv.getRange('B9').values=[['Grand total']];piv.getRange('C9').formulas=[['=SUM(C5:C8)']];
piv.getRange('F8').values=[['Grand average']];piv.getRange('G8').formulas=[[`=AVERAGE(Payments!D2:D${p})`]];
piv.getRange('C5:C9').setNumberFormat(currency);piv.getRange('G5:G8').setNumberFormat('0.00');
piv.getRange('B:C').format.columnWidth=26;piv.getRange('F:G').format.columnWidth=26;
const audit=sheets.Reconciliation;
audit.getRange('B2').values=[['Independent SQL reconciliation']];audit.getRange('B4:E4').values=[['Region','Excel INR','SQL INR','Difference INR']];
data.regional.forEach(([region,total],i)=>{const r=i+5;audit.getRange(`B${r}:E${r}`).values=[[region,null,total,null]];audit.getRange(`C${r}`).formulas=[[`=SUMIFS(Cleaned_Master!$F$2:$F$${n},Cleaned_Master!$I$2:$I$${n},B${r})`]];audit.getRange(`E${r}`).formulas=[[`=C${r}-D${r}`]];});
audit.getRange('B12:E12').values=[['Plan','Excel delay','SQL delay','Difference days']];
data.plan_delay.forEach(([plan,total],i)=>{const r=i+13;audit.getRange(`B${r}:E${r}`).values=[[plan,null,total,null]];audit.getRange(`C${r}`).formulas=[[`=AVERAGEIFS(Payments!$D$2:$D$${p},Payments!$C$2:$C$${p},B${r})`]];audit.getRange(`E${r}`).formulas=[[`=C${r}-D${r}`]];});
audit.getRange('C5:E8').setNumberFormat('0.00');audit.getRange('C13:E15').setNumberFormat('0.0000');audit.getRange('B:E').format.columnWidth=24;
audit.getRange('E5:E15').conditionalFormats.addCustom('=ABS(E5)>0.005',{fill:'#FCE9E7',font:{color:'#9B2727',bold:true}});
for(const sheet of [overview,piv,audit]){sheet.getRange('B2:H2').format.font={name:'Arial',size:14,bold:true,color:ink};}
for(const [sheet,range] of [[overview,'B6:C6'],[piv,'B4:C4'],[piv,'F4:G4'],[audit,'B4:E4'],[audit,'B12:E12']])sheet.getRange(range).format={fill:ink,font:{color:'#FFFFFF',bold:true,name:'Arial',size:10},rowHeight:27};
const originalAmount=sheets.Cleaned_Master.getRange('F2').values[0][0];
const originalTotal=overview.getRange('C7').values[0][0];
sheets.Cleaned_Master.getRange('F2').values=[[originalAmount+100]];
wb.recalculate();
if(Math.abs(overview.getRange('C7').values[0][0]-originalTotal-100)>.005)throw new Error('Input-change recalculation failed');
sheets.Cleaned_Master.getRange('F2').values=[[originalAmount]];
const originalCustomer=sheets.Cleaned_Master.getRange('B2').values[0][0];
sheets.Cleaned_Master.getRange('B2').values=[['UNKNOWN_TEST']];
wb.recalculate();
if(sheets.Cleaned_Master.getRange('I2').values[0][0]!=='UNMAPPED')throw new Error('Missing-key handling failed');
sheets.Cleaned_Master.getRange('B2').values=[[originalCustomer]];
wb.recalculate();
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!',options:{useRegex:true,maxResults:20},summary:'Formula error scan'});
await fs.mkdir(path.join(root,'reports/workbook'),{recursive:true});
await fs.writeFile(path.join(root,'reports/workbook/recalculation_checks.json'),JSON.stringify({engine:'artifact-tool',amount_edit_propagates:true,missing_key_visible:true,test_edits_restored:true,native_excel:'Deferred by user'},null,2));
await fs.writeFile(path.join(root,'reports/workbook/formula_scan.json'),errors.ndjson);
console.log((await wb.inspect({kind:'table',range:'Reconciliation!B4:E15',include:'values,formulas',tableMaxRows:12,tableMaxCols:4})).ndjson);
for(const name of names){const range=name==='Overview'?'B2:J23':name==='Reconciliation'?'B2:F16':name==='Audit_Pivots'?'B2:H10':name==='Cleaned_Master'?'A1:J12':name==='Customers'?'A1:D12':'A1:D12';const png=await wb.render({sheetName:name,range,scale:1.3});await fs.writeFile(path.join(root,'reports/workbook',name+'.png'),new Uint8Array(await png.arrayBuffer()));}
const output=await SpreadsheetFile.exportXlsx(wb);await output.save(path.join(root,'excel/RevPulse_Validation_Audit.xlsx'));
console.log('Workbook exported');
